import os
from abc import ABC, abstractmethod
from hmac import HMAC

import argon2


class Credentials:
    """
    Credentials for Pbkdf.

    Users are encouraged to use strong passwords.
    Those are hard to remember and to type into a keyboard.
    Tey are best generated by and stored in a password managered and entered with a QR code.

    As an additional protection, users can type in an additional secret, wich also goes into the kdf.
    """

    password: str
    secret: str

    def __init__(self, password: str, secret: str) -> None:
        self.password = password
        self.secret = secret


class Pbkdf(ABC):
    "Base class for a Password Based Key Derivation Function (PBKDF)."

    @staticmethod
    def create() -> Pbkdf:
        return PbkdfArgon2.create()

    @staticmethod
    def credentials_to_bytes(credentials: Credentials) -> bytes:
        """
        Canonical way to convert credentials into bytes as input for the PBKDF algo.
        This method is not expected to change and therefore implicit (not serialized).
        """

        key = ("seedwarden" + credentials.secret).encode()
        msg = credentials.password.encode()
        digest = HMAC(key, msg, "sha256").digest()
        return digest

    @abstractmethod
    def digest(self, credentials: Credentials) -> bytes:
        "Apply the PBKDF to credentials to get the output."

    @abstractmethod
    def serialize(self) -> dict:
        'Convert to a jsonable object that contains an entry "algo".'

    @staticmethod
    def deserialize(serialized: dict) -> Pbkdf:
        "Deserialize."

        algo: str = serialized["algo"]
        match algo:
            case PbkdfArgon2.ALGO:
                return PbkdfArgon2.deserialize(serialized)
            case _:
                raise ValueError(f"{algo} is not supported by this release.")


class PbkdfArgon2(Pbkdf):
    "Argon2 implementation."

    ALGO = "Argon2"

    # Argon2 parameters
    _salt: bytes
    _time_cost: int
    _memory_cost: int
    _parallelism: int
    _hash_len: int
    _type: argon2.low_level.Type
    _version: int

    @staticmethod
    def create() -> PbkdfArgon2:
        "Create a new instance with default parameters and random salt."
        # currently using the recommended defaults for "memory-constrained environments".
        # needs testing on a Pi Zero, should 1 to 3s. memory almost certainly too high
        r = PbkdfArgon2()
        r._salt = os.urandom(16)
        r._time_cost = 3
        r._memory_cost = 64 * 1024
        r._parallelism = 3
        r._hash_len = 32
        r._type = argon2.low_level.Type.ID
        r._version = argon2.low_level.ARGON2_VERSION
        return r

    def serialize(self) -> dict:
        return {
            "algo": PbkdfArgon2.ALGO,
            "salt": Convert.bytes_to_base64str(self._salt),
            "time-cost": self._time_cost,
            "memory-cost": self._memory_cost,
            "parallelism": self._parallelism,
            "hash-len": self._hash_len,
            "type": self._type.value,
            "version": self._version,
        }

    @staticmethod
    def deserialize(serialized: dict) -> PbkdfArgon2:
        algo = serialized["algo"]
        if algo != PbkdfArgon2.ALGO:
            raise ValueError(f"Expected algo {PbkdfArgon2.ALGO}, got {algo}")
        r = PbkdfArgon2()
        r._salt = Convert.base64str_to_bytes(serialized["salt"])
        r._time_cost = serialized["time-cost"]
        r._memory_cost = serialized["memory-cost"]
        r._parallelism = serialized["parallelism"]
        r._hash_len = serialized["hash-len"]
        r._type = argon2.low_level.Type(serialized["type"])
        r._version = serialized["version"]
        return r

    def digest(self, credentials: Credentials) -> bytes:
        secret = Pbkdf.credentials_to_bytes(credentials)
        hash = argon2.low_level.hash_secret_raw(
            secret=secret,
            salt=self._salt,
            time_cost=self._time_cost,
            memory_cost=self._memory_cost,
            parallelism=self._parallelism,
            hash_len=self._hash_len,
            type=self._type,
            version=self._version,
        )
        return hash
